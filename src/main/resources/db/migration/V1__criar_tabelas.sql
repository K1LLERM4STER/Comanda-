-- Schema inicial do sistema de comandas

CREATE TABLE estabelecimento (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(255) NOT NULL,
    cnpj      VARCHAR(255) NOT NULL,
    sobre     VARCHAR(255),
    endereco  VARCHAR(255) NOT NULL,
    email     VARCHAR(255) NOT NULL,
    ativo     BOOLEAN,
    CONSTRAINT uk_estabelecimento_cnpj UNIQUE (cnpj)
);

CREATE TABLE usuario (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               VARCHAR(255) NOT NULL,
    email              VARCHAR(255) NOT NULL,
    senha              VARCHAR(255) NOT NULL,
    estabelecimento_id BIGINT NOT NULL REFERENCES estabelecimento (id),
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

CREATE TABLE cliente (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   VARCHAR(255) NOT NULL,
    email  VARCHAR(255) NOT NULL,
    senha  VARCHAR(255) NOT NULL,
    cpf    VARCHAR(255) NOT NULL,
    CONSTRAINT uk_cliente_email UNIQUE (email),
    CONSTRAINT uk_cliente_cpf   UNIQUE (cpf)
);

CREATE TABLE grupo (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao          VARCHAR(255) NOT NULL,
    estabelecimento_id BIGINT NOT NULL REFERENCES estabelecimento (id)
);

CREATE TABLE produto (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id           BIGINT NOT NULL REFERENCES grupo (id),
    estabelecimento_id BIGINT NOT NULL REFERENCES estabelecimento (id),
    unidade            VARCHAR(255) NOT NULL,
    descricao          VARCHAR(255) NOT NULL,
    estoque            BIGINT NOT NULL CHECK (estoque >= 0),
    pvenda             NUMERIC(10, 2) NOT NULL CHECK (pvenda > 0)
);

CREATE TABLE mesa (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id BIGINT NOT NULL REFERENCES estabelecimento (id),
    numero_mesa        VARCHAR(255) NOT NULL,
    CONSTRAINT uk_mesa_estabelecimento_numero UNIQUE (estabelecimento_id, numero_mesa)
);

CREATE TABLE comanda (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id         BIGINT REFERENCES cliente (id),
    usuario_id         BIGINT NOT NULL REFERENCES usuario (id),
    estabelecimento_id BIGINT NOT NULL REFERENCES estabelecimento (id),
    mesa_id            BIGINT NOT NULL REFERENCES mesa (id),
    status             VARCHAR(255) NOT NULL CHECK (status IN ('ABERTA', 'FECHADA', 'CANCELADA')),
    data_abertura      TIMESTAMP(6),
    data_fechamento    TIMESTAMP(6)
);

-- Garante no banco que cada mesa tenha no maximo UMA comanda aberta
CREATE UNIQUE INDEX uq_comanda_mesa_aberta ON comanda (mesa_id) WHERE status = 'ABERTA';

CREATE TABLE item_comanda (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanda_id     BIGINT NOT NULL REFERENCES comanda (id),
    produto_id     BIGINT NOT NULL REFERENCES produto (id),
    quantidade     INTEGER NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(10, 2) NOT NULL CHECK (valor_unitario > 0)
);

CREATE INDEX idx_produto_grupo        ON produto (grupo_id);
CREATE INDEX idx_comanda_estab_status ON comanda (estabelecimento_id, status);
CREATE INDEX idx_item_comanda_comanda ON item_comanda (comanda_id);
